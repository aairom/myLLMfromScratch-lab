"""The gallery page ``index.html`` next to the GIFs: every animation with its caption and its written guides."""
from __future__ import annotations

import html
from pathlib import Path

from animgen.registry import ALL_SCENES
from animgen.scene import Scene
from docsgen import catalog

CSS = """
body{font:15px/1.6 -apple-system,"Segoe UI",system-ui,sans-serif;color:#1f2328;background:#fff;margin:0}
main{max-width:880px;margin:0 auto;padding:24px 20px 48px}
h1{font-size:26px;margin:0 0 4px}
.lead{color:#57606a;margin:0 0 24px}
section{border:1px solid #e5e7eb;border-radius:8px;background:#f7f8fa;padding:16px;margin:0 0 24px}
section h2{font-size:18px;margin:0 0 4px}
section p{margin:4px 0 12px;color:#57606a}
img{display:block;width:100%;height:auto;border:1px solid #e5e7eb;border-radius:6px;background:#fff}
ol{color:#57606a;margin:12px 0 8px;padding-left:22px}
.links a{margin-right:14px}
a{color:#3b82d4}
footer{text-align:center;font-size:12px;color:#57606a;border-top:1px solid #e5e7eb;padding-top:12px;margin-top:32px}
"""


def _section(scene: Scene, existing: set[str]) -> str:
    sub = catalog.get(scene.number)
    steps = "".join(f"<li>{html.escape(c)}</li>" for c in scene.captions)
    links = [f'<a href="../{html.escape(sub.explanation_html)}">Explanation</a>',
             f'<a href="../{html.escape(sub.guide_html)}">Implementation guide</a>',
             f'<a href="{html.escape(scene.filename)}">Open the GIF</a>']
    if scene.filename in existing:
        picture = (f'<img src="{html.escape(scene.filename)}" width="800" height="450" loading="lazy" '
                   f'alt="Animation: {html.escape(scene.title)}. Steps: {html.escape("; ".join(scene.captions))}">')
    else:
        picture = "<p>This GIF has not been generated yet. Run scripts/generate-animations.sh.</p>"
    return (f'<section id="{html.escape(scene.key)}"><h2>{html.escape(scene.kicker)}: {html.escape(scene.title)}</h2>'
            f"<p>{html.escape(sub.summary)}</p>{picture}<ol>{steps}</ol>"
            f'<div class="links">{"".join(links)}</div></section>')


def gallery_html(existing: set[str]) -> str:
    """The standalone gallery; ``existing`` is the set of GIF file names present next to it."""
    body = "".join(_section(s, existing) for s in ALL_SCENES)
    return ('<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width, initial-scale=1">'
            f"<title>LLM from scratch - animations</title><style>{CSS}</style></head><body><main>"
            "<h1>LLM from scratch: animations</h1>"
            '<p class="lead">One looping animation per sub-task. Every number comes from the project\'s own code. '
            'Each GIF pauses briefly after every step; the dots at the top right show where you are. '
            '<a href="index.html">Back to top</a> | <a href="../index.html">All written documents</a></p>'
            f"{body}<footer>Generated by animgen - see Docs/Architecture.md</footer></main></body></html>")


def write_gallery(out_dir: Path) -> Path:
    """Write ``index.html`` into ``out_dir`` (links point to the GIFs that exist there)."""
    out_dir.mkdir(parents=True, exist_ok=True)
    existing = {p.name for p in out_dir.glob("*.gif")}
    path = out_dir / "index.html"
    path.write_text(gallery_html(existing), encoding="utf-8")
    return path
