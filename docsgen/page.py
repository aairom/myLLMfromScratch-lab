"""The standalone HTML shell: one self-contained file per document, no external assets."""
from __future__ import annotations

import html
from dataclasses import dataclass
from typing import Optional

from docsgen import catalog, theme
from docsgen.render import Rendered, toc_html

PROJECT_NAME = "LLM From Scratch Lab"

# The learner's path through the project, in the order the sub-tasks build on each other.
KIND_EXPLANATION = "explanation"
KIND_GUIDE = "guide"
KIND_LABEL = {KIND_EXPLANATION: "Scientific explanation", KIND_GUIDE: "Implementation guide"}


@dataclass(frozen=True)
class PageMeta:
    """Everything the shell needs besides the rendered body."""

    title: str
    kicker: str
    lede: str
    badges: tuple[str, ...] = ()
    subnav: tuple[tuple[str, str, bool], ...] = ()  # (label, href, is_current)
    path_html: str = ""                              # pipeline position (ol.path), optional


def _e(text: str) -> str:
    return html.escape(text, quote=True)


def path_html(current: Optional[int], kind: str) -> str:
    """The ten sub-tasks as an ordered list; the current one carries ``aria-current``."""
    items = []
    for sub in catalog.SUBTASKS:
        href = sub.explanation_html if kind == KIND_EXPLANATION else sub.guide_html
        mark = ' aria-current="step"' if sub.number == current else ""
        items.append(f'<li{mark}><a href="{_e(href)}">{_e(sub.title)}</a></li>')
    return f'<nav aria-label="Position in the project path"><ol class="path">{"".join(items)}</ol></nav>'


def subtask_meta(sub: catalog.SubTask, kind: str, rendered: Rendered, extra_badges: tuple[str, ...] = ()) -> PageMeta:
    """Header content for a sub-task page, with links to its sibling document and neighbours."""
    prev, nxt = catalog.neighbours(sub.number)
    explanation = kind == KIND_EXPLANATION
    nav: list[tuple[str, str, bool]] = [("Index", "index.html", False)]
    nav.append(("Explanation", sub.explanation_html, explanation))
    nav.append(("Implementation guide", sub.guide_html, not explanation))
    if prev:
        nav.append((f"\u2190 {prev.number}. {prev.title}", prev.explanation_html if explanation else prev.guide_html, False))
    if nxt:
        nav.append((f"{nxt.number}. {nxt.title} \u2192", nxt.explanation_html if explanation else nxt.guide_html, False))
    return PageMeta(
        title=f"{sub.number}. {rendered.title or sub.title}",
        kicker=f"{PROJECT_NAME} \u00b7 Sub-task {sub.number} of {len(catalog.SUBTASKS)} \u00b7 {KIND_LABEL[kind]}",
        lede=sub.summary,
        badges=extra_badges,
        subnav=tuple(nav),
        path_html=path_html(sub.number, kind),
    )


def build_page(meta: PageMeta, rendered: Rendered, footer_note: str = "") -> str:
    """Wrap a rendered body into a complete HTML5 document."""
    badges = "".join(f"<li>{_e(b)}</li>" for b in meta.badges)
    badge_html = f'<ul class="badges" aria-label="Key facts">{badges}</ul>' if badges else ""
    nav_items = "".join(
        f'<a href="{_e(href)}"{" aria-current=\"page\"" if current else ""}>{_e(label)}</a>'
        for label, href, current in meta.subnav
    )
    subnav = f'<nav class="subnav" aria-label="Documents">{nav_items}</nav>' if nav_items else ""
    toc = toc_html(rendered.toc)
    toc_block = f'<nav class="toc" aria-label="On this page"><h2>On this page</h2>{toc}</nav>' if toc else ""
    layout_class = "layout" if toc else "layout single"
    note = f"<p>{_e(footer_note)}</p>" if footer_note else ""
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<title>{_e(meta.title)} \u2013 {PROJECT_NAME}</title>
<style>
{theme.stylesheet()}
.layout.single {{ grid-template-columns: minmax(0, 1fr); }}
</style>
</head>
<body>
<a class="skip-link" href="#content">Skip to main content</a>
<header class="site">
<div class="wrap">
<p class="kicker">{_e(meta.kicker)}</p>
<h1>{_e(meta.title)}</h1>
<p class="lede">{_e(meta.lede)}</p>
{badge_html}
{subnav}
</div>
</header>
<div class="wrap {layout_class}">
{toc_block}
<main id="content" tabindex="-1">
{meta.path_html}
{rendered.body}
</main>
</div>
<footer class="site">
<div class="wrap">
{note}
<p>Generated by <code>scripts/build-docs.sh</code> from <code>Docs/subtasks/</code>. Made with IBM Bob.</p>
</div>
</footer>
</body>
</html>
"""
